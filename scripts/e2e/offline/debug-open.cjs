const L = require('./lib.cjs')
;(async () => {
  const dave = new L.ApiUser('dave'); await dave.login()
  const open = await dave.req('POST', '/conversations/direct/', { user_id: L.acc.accounts.carol.public_id })
  console.log('open', open.status, open.data.id)
  const b = await L.browser(); const p = await b.newPage({ viewport: { width: 1280, height: 860 } })
  await L.uiLogin(p, 'http://127.0.0.1:4176', 'carol'); console.log('url', p.url())
  await p.goto('http://127.0.0.1:4176/messenger?conversation=' + open.data.id, { waitUntil: 'domcontentloaded' })
  await L.sleep(8000)
  await p.screenshot({ path: L.OUT + '/debug-open.png' })
  console.log((await p.evaluate(() => document.body.innerText)).slice(0, 800))
  console.log(await p.evaluate(() => [...document.querySelectorAll('textarea,input')].map(e => e.tagName + ':' + e.getAttribute('aria-label') + ':' + e.getAttribute('placeholder'))))
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
